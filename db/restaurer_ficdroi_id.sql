-- Restaure la clé "FicDroi_Id" de T_Fichier_Droits, perdue lors du réimport (le code API s'en sert
-- pour modifier / supprimer / cocher une ligne de droit). Rejouable : ne fait rien si elle existe.
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns
                  WHERE table_schema = 'public' AND table_name = 'T_Fichier_Droits' AND column_name = 'FicDroi_Id') THEN
    ALTER TABLE public."T_Fichier_Droits"
      ADD COLUMN "FicDroi_Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;
  END IF;
END $$;
NOTIFY pgrst, 'reload schema';
